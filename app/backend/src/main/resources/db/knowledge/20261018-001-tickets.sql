CREATE TABLE KNOWLEDGE_TICKET (
    ID UUID PRIMARY KEY,
    AUTHOR_ID UUID NOT NULL REFERENCES ACCOUNT(ID),
    ORGANIZATION_ID UUID NOT NULL REFERENCES ORGANIZATION(ID),
    AUTHOR_NAME VARCHAR(200) NOT NULL,
    SUBMISSION_ID UUID NOT NULL,
    CONTENT TEXT NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CLASSIFICATION_STATUS VARCHAR(20) NOT NULL CHECK (CLASSIFICATION_STATUS IN ('PENDING','PROCESSING','RETRYING','COMPLETE','FAILED')),
    ATTRIBUTES TEXT NOT NULL DEFAULT '[]',
    ATTEMPTS INTEGER NOT NULL DEFAULT 0,
    NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    LEASE_TOKEN UUID,
    LEASE_UNTIL TIMESTAMP WITH TIME ZONE,
    UNIQUE (AUTHOR_ID, SUBMISSION_ID)
);
CREATE INDEX KNOWLEDGE_TICKET_ORGANIZATION ON KNOWLEDGE_TICKET (ORGANIZATION_ID, CREATED_AT);
CREATE INDEX KNOWLEDGE_TICKET_QUEUE ON KNOWLEDGE_TICKET (NEXT_ATTEMPT_AT) WHERE CLASSIFICATION_STATUS IN ('PENDING', 'RETRYING', 'PROCESSING');
