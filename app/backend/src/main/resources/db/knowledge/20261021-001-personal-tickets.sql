ALTER TABLE KNOWLEDGE_TICKET ALTER COLUMN ORGANIZATION_ID DROP NOT NULL;
CREATE INDEX KNOWLEDGE_TICKET_PERSONAL_BROWSE ON KNOWLEDGE_TICKET (AUTHOR_ID, CREATED_AT DESC, ID DESC)
    WHERE ORGANIZATION_ID IS NULL;
CREATE INDEX KNOWLEDGE_TICKET_PERSONAL_TYPE ON KNOWLEDGE_TICKET (AUTHOR_ID, (CONTENT::jsonb->>'template'), CREATED_AT DESC, ID DESC)
    WHERE ORGANIZATION_ID IS NULL;
--changeset betterf:20261021-002-personal-ownership splitStatements:false
CREATE FUNCTION PRESERVE_PERSONAL_TICKET() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.ORGANIZATION_ID IS NULL AND
       (NEW.ORGANIZATION_ID IS NOT NULL OR NEW.AUTHOR_ID <> OLD.AUTHOR_ID) THEN
        RAISE EXCEPTION 'Personal ticket ownership is immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
--changeset betterf:20261021-003-personal-trigger
CREATE TRIGGER PERSONAL_TICKET_IMMUTABLE BEFORE UPDATE ON KNOWLEDGE_TICKET
    FOR EACH ROW EXECUTE FUNCTION PRESERVE_PERSONAL_TICKET();
