    ID UUID PRIMARY KEY,
    ACCOUNT_ID UUID NOT NULL REFERENCES ACCOUNT(ID),
    PROVIDER VARCHAR(20) NOT NULL CHECK (PROVIDER IN ('linkedin', 'facebook')),
    SUBJECT_ID VARCHAR(255) NOT NULL,
    UNIQUE (PROVIDER, SUBJECT_ID)
);
CREATE INDEX OAUTH_IDENTITY_ACCOUNT ON OAUTH_IDENTITY (ACCOUNT_ID);
-- Individual classification is permanent, even through direct persistence updates.
--changeset betterf:20261021-002-individual-immutability splitStatements:false
CREATE FUNCTION PRESERVE_INDIVIDUAL_ACCOUNT() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.ACCOUNT_TYPE = 'INDIVIDUAL' AND NEW.ACCOUNT_TYPE <> 'INDIVIDUAL' THEN
        RAISE EXCEPTION 'Individual account type is immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
--changeset betterf:20261021-003-individual-trigger
CREATE TRIGGER ACCOUNT_INDIVIDUAL_IMMUTABLE BEFORE UPDATE ON ACCOUNT
    FOR EACH ROW EXECUTE FUNCTION PRESERVE_INDIVIDUAL_ACCOUNT();
