CREATE TABLE WORKSPACE_MEMBERSHIP (
    ID UUID PRIMARY KEY,
    ACCOUNT_ID UUID NOT NULL REFERENCES ACCOUNT(ID),
    WORKSPACE_ID UUID NOT NULL REFERENCES WORKSPACE(ID),
    ROLE VARCHAR(20) NOT NULL CHECK (ROLE IN ('OWNER', 'MEMBER')),
    ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (ACCOUNT_ID, WORKSPACE_ID)
);
CREATE INDEX WORKSPACE_MEMBERSHIP_WORKSPACE ON WORKSPACE_MEMBERSHIP(WORKSPACE_ID, ACTIVE);
INSERT INTO WORKSPACE_MEMBERSHIP (ID, ACCOUNT_ID, WORKSPACE_ID, ROLE)
SELECT gen_random_uuid(), A.ID, A.ORGANIZATION_ID, CASE WHEN A.ACCESS_ROLE = 'ADMIN' THEN 'OWNER' ELSE 'MEMBER' END
FROM ACCOUNT A JOIN WORKSPACE W ON W.ID = A.ORGANIZATION_ID
WHERE A.STATUS = 'ACTIVE' AND W.STATUS = 'ACTIVE';
ALTER TABLE ACCOUNT ADD COLUMN DEFAULT_WORKSPACE_ID UUID REFERENCES WORKSPACE(ID);
-- Legacy owners retain their existing workspace as default. Other active accounts get a private default.
UPDATE ACCOUNT SET DEFAULT_WORKSPACE_ID = ORGANIZATION_ID WHERE STATUS = 'ACTIVE' AND ACCESS_ROLE = 'ADMIN';
INSERT INTO WORKSPACE (ID, NAME, STATUS)
SELECT A.ID, 'My workspace', 'ACTIVE' FROM ACCOUNT A WHERE A.STATUS = 'ACTIVE' AND A.DEFAULT_WORKSPACE_ID IS NULL;
UPDATE ACCOUNT SET DEFAULT_WORKSPACE_ID = ID WHERE STATUS = 'ACTIVE' AND DEFAULT_WORKSPACE_ID IS NULL;
INSERT INTO WORKSPACE_MEMBERSHIP (ID, ACCOUNT_ID, WORKSPACE_ID, ROLE)
SELECT gen_random_uuid(), ID, DEFAULT_WORKSPACE_ID, 'OWNER' FROM ACCOUNT WHERE STATUS = 'ACTIVE'
ON CONFLICT (ACCOUNT_ID, WORKSPACE_ID) DO NOTHING;
UPDATE KNOWLEDGE_TICKET T SET WORKSPACE_ID = A.DEFAULT_WORKSPACE_ID FROM ACCOUNT A WHERE T.AUTHOR_ID = A.ID AND T.WORKSPACE_ID IS NULL;
ALTER TABLE KNOWLEDGE_TICKET ALTER COLUMN WORKSPACE_ID SET NOT NULL;
ALTER TABLE ACCOUNT DROP COLUMN ORGANIZATION_ID, DROP COLUMN ACCOUNT_TYPE, DROP COLUMN ACCESS_ROLE, DROP COLUMN PROFESSIONAL_ROLE;
-- Pending legacy signup workspaces contain no active membership/content; activation provisions the default.
DELETE FROM WORKSPACE W WHERE W.STATUS = 'PENDING' AND NOT EXISTS (SELECT 1 FROM KNOWLEDGE_TICKET T WHERE T.WORKSPACE_ID = W.ID)
AND NOT EXISTS (SELECT 1 FROM TEAM_INVITATION I WHERE I.WORKSPACE_ID = W.ID);
DROP INDEX KNOWLEDGE_TICKET_PERSONAL_BROWSE;
